func TestRun_ReportsUnreadableExclusions(t *testing.T) {
	setUpModule(t, map[string]string{"coverage.out": "mode: set\n"})
	if err := os.MkdirAll("exclusions-folder", 0o750); err != nil {
		t.Fatal(err)
	}
	var errorOutput bytes.Buffer
	exitCode := run([]string{"-exclusions", "exclusions-folder", "coverage.out"}, &errorOutput, &errorOutput)
	if exitCode != exitUsage {
		t.Errorf("exit code %d, want %d", exitCode, exitUsage)
	}
}

func TestParseBlock(t *testing.T) {
	tests := []struct {
		name         string
		line         string
		wantPosition string
		wantBlock    block
		wantErr      bool
	}{
		{"run block", "m/a.go:1.2,3.4 2 7", "m/a.go:1.2,3.4", block{"m/a.go", 2, true}, false},
		{"unrun block", "m/a.go:1.2,3.4 2 0", "m/a.go:1.2,3.4", block{file: "m/a.go", statements: 2}, false},
		{"too few fields", "m/a.go:1.2,3.4 2", "", block{}, true},
		{"no colon", "m/a.go 2 1", "", block{}, true},
		{"statements not a number", "m/a.go:1.2,3.4 two 1", "", block{}, true},
		{"run count not a number", "m/a.go:1.2,3.4 2 once", "", block{}, true},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			position, parsed, err := parseBlock(test.line)
			if (err != nil) != test.wantErr {
				t.Fatalf("error %v, want error: %v", err, test.wantErr)
			}
			if position != test.wantPosition || parsed != test.wantBlock {
				t.Errorf("got %q %+v, want %q %+v", position, parsed, test.wantPosition, test.wantBlock)
			}
		})
	}
}

func TestTallyPercent_EmptyIsFullyCovered(t *testing.T) {
	if percent := (tally{}).percent(); percent != 100 {
		t.Errorf("percent of no statements is %v, want 100", percent)
	}
}

func FuzzParseBlock(f *testing.F) {
	f.Add("m/a.go:1.2,3.4 2 7")
	f.Add("m/a.go 2 1")
	f.Add("")
	f.Fuzz(func(t *testing.T, line string) {
		position, parsed, err := parseBlock(line)
		if err != nil {
			return
		}
		if !strings.HasPrefix(position, parsed.file+":") {
			t.Errorf("position %q doesn't start with file %q", position, parsed.file)
		}
	})
}
