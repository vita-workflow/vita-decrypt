const testModule = "example.com/module"

// setUpModule makes a temporary module root holding the given files, and changes into it for the test.
func setUpModule(t *testing.T, files map[string]string) {
	t.Helper()
	root := t.TempDir()
	files["go.mod"] = "module " + testModule + "\n\ngo 1.26\n"
	for name, contents := range files {
		filePath := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(filePath), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filePath, []byte(contents), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	t.Chdir(root)
}

func assertContainsAll(t *testing.T, label, text string, wants []string) {
	t.Helper()
	for _, want := range wants {
		if !strings.Contains(text, want) {
			t.Errorf("%s don't contain %q:\n%s", label, want, text)
		}
	}
}

func profileLine(file, position string, statements, runCount int) string {
	return fmt.Sprintf("%s/%s:%s %d %d\n", testModule, file, position, statements, runCount)
}

func TestRun(t *testing.T) {
	linuxProfile := "mode: atomic\n" +
		profileLine("app/shared.go", "1.1,2.2", 9, 1) +
		profileLine("app/shared.go", "3.1,4.2", 1, 0) +
		profileLine("app/linux.go", "1.1,2.2", 5, 1) +
		profileLine("tool/main.go", "1.1,2.2", 1, 1)
	windowsProfile := "mode: atomic\n" +
		profileLine("app/shared.go", "1.1,2.2", 9, 0) +
		profileLine("app/shared.go", "3.1,4.2", 1, 3) +
		profileLine("app/windows.go", "1.1,2.2", 5, 0)

	tests := []struct {
		name           string
		arguments      []string
		exclusions     string
		wantExitCode   int
		wantOutput     []string
		wantErrorTexts []string
	}{
		{
			name:         "a block run on either platform counts as covered",
			arguments:    []string{"-minimum", "70", "linux.out", "windows.out"},
			wantExitCode: exitPassed,
			wantOutput:   []string{"75.0%     15/20     example.com/module/app  ok", "total  ok"},
		},
		{
			name:         "a package below the minimum fails",
			arguments:    []string{"linux.out", "windows.out"},
			wantExitCode: exitBelowMinimum,
			wantOutput: []string{
				"example.com/module/app  FAIL (minimum 90.0%)",
				"100.0%      1/1      example.com/module/tool  ok",
			},
		},
		{
			name:         "an excluded file doesn't count",
			arguments:    []string{"linux.out", "windows.out"},
			exclusions:   "# Excluded files\n\napp/windows.go  # needs a real display\n",
			wantExitCode: exitPassed,
			wantOutput:   []string{"100.0%     15/15     example.com/module/app  ok"},
		},
		{
			name:           "an exclusion without a reason is rejected",
			arguments:      []string{"linux.out"},
			exclusions:     "app/windows.go\n",
			wantExitCode:   exitUsage,
			wantErrorTexts: []string{"needs a reason"},
		},
		{
			name:           "no profiles is a usage error",
			wantExitCode:   exitUsage,
			wantErrorTexts: []string{"give at least one coverage profile"},
		},
		{
			name:           "an unknown flag is a usage error",
			arguments:      []string{"-unknown"},
			wantExitCode:   exitUsage,
			wantErrorTexts: []string{"flag provided but not defined"},
		},
		{
			name:           "a missing profile is a usage error",
			arguments:      []string{"missing.out"},
			wantExitCode:   exitUsage,
			wantErrorTexts: []string{"missing.out"},
		},
		{
			name:           "a malformed profile is a usage error",
			arguments:      []string{"malformed.out"},
			wantExitCode:   exitUsage,
			wantErrorTexts: []string{"malformed.out:2: not a coverage profile line"},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			files := map[string]string{
				"linux.out":     linuxProfile,
				"windows.out":   windowsProfile,
				"malformed.out": "mode: set\nnot a block\n",
			}
			if test.exclusions != "" {
				files[".github/coverage-exclusions.txt"] = test.exclusions
			}
			setUpModule(t, files)

			var output, errorOutput bytes.Buffer
			exitCode := run(test.arguments, &output, &errorOutput)

			if exitCode != test.wantExitCode {
				t.Errorf("exit code %d, want %d\noutput:\n%s\nerrors:\n%s",
					exitCode, test.wantExitCode, &output, &errorOutput)
			}
			assertContainsAll(t, "output", output.String(), test.wantOutput)
			assertContainsAll(t, "errors", errorOutput.String(), test.wantErrorTexts)
		})
	}
}

func TestRun_SkipsGeneratedFiles(t *testing.T) {
	setUpModule(t, map[string]string{
		"app/generated.go": "// Code generated by a tool. DO NOT EDIT.\n\npackage app\n",
		"coverage.out": "mode: set\n" +
			profileLine("app/generated.go", "1.1,2.2", 5, 0) +
			profileLine("app/written.go", "1.1,2.2", 5, 1),
	})
	var output bytes.Buffer
	if exitCode := run([]string{"coverage.out"}, &output, &output); exitCode != exitPassed {
		t.Fatalf("exit code %d, want %d:\n%s", exitCode, exitPassed, &output)
	}
	if !strings.Contains(output.String(), "100.0%      5/5      example.com/module/app") {
		t.Errorf("generated file was counted:\n%s", &output)
	}
}

func TestRun_RequiresModuleLine(t *testing.T) {
	setUpModule(t, map[string]string{"coverage.out": "mode: set\n"})
	if err := os.WriteFile("go.mod", []byte("go 1.26\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	var errorOutput bytes.Buffer
	if exitCode := run([]string{"coverage.out"}, &errorOutput, &errorOutput); exitCode != exitUsage {
		t.Errorf("exit code %d, want %d", exitCode, exitUsage)
	}
	if !strings.Contains(errorOutput.String(), "has no module line") {
		t.Errorf("errors don't explain the missing module line:\n%s", &errorOutput)
	}
}

